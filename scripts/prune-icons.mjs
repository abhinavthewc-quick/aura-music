#!/usr/bin/env node
/**
 * Prune src/styles/icons.css down to the icons Aura actually uses.
 *
 * The vendored sheet is Font Awesome Free 6.4.0: 179 icons, 128 KB raw. The
 * generator that produced it (scripts/vendor-ui-assets.mjs) is no longer in the
 * repo, so this script is the supported way to regenerate the sheet.
 *
 * Nothing is lost: the complete vendored sheet lives at tooling/icons-full.css
 * and this script always reads from there, so any icon can be restored by
 * adding its name to the usage set and re-running.
 *
 * Usage:
 *   node scripts/prune-icons.mjs            # report only
 *   node scripts/prune-icons.mjs --apply    # rewrite src/styles/icons.css
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FULL = join(ROOT, 'tooling/icons-full.css');
const OUT = join(ROOT, 'src/styles/icons.css');

// Icon names assembled at runtime from ternaries or parameters, so a static
// scan cannot see them. Keep in sync with the dynamic sites in src/:
//   src/features/radio.ts   fa-${canPause ? 'pause' : 'play'}, fa-${active ? 'volume-high' : 'play'}
//   src/features/lyrics.ts  fa-align-${alignMode}  (left | center)
//   src/core/dom.ts         toast(msg, icon = 'circle-check') and its call sites
const DYNAMIC = [
  'play', 'pause', 'volume-high',
  'align-left', 'align-center',
  'circle-check', 'circle-exclamation', 'circle-info', 'triangle-exclamation',
  'shuffle', 'repeat', 'microphone', 'list-check',
];

// Style modifiers, not icon names.
const MODIFIERS = new Set(['solid', 'regular', 'brands', 'spin', 'pulse']);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry.startsWith('.')) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (['.ts', '.html', '.css'].includes(extname(path))) out.push(path);
  }
  return out;
}

// The icon sheet itself must never be scanned: it defines every name, so
// including it would mark all of them "used" and prune nothing.
const files = [
  join(ROOT, 'index.html'),
  join(ROOT, 'admin.html'),
  join(ROOT, 'rooms.html'),
  ...walk(join(ROOT, 'src')).filter((file) => file !== OUT),
];

const used = new Set(DYNAMIC);
for (const file of files) {
  const text = readFileSync(file, 'utf8');
  for (const match of text.matchAll(/fa-([a-z0-9-]+)/g)) {
    const name = match[1];
    if (!MODIFIERS.has(name)) used.add(name);
  }
}

const full = readFileSync(FULL, 'utf8');
const lines = full.split('\n');

// The vendored sheet groups aliases onto one rule:
//   .fa-solid.fa-arrows-rotate,.fa-solid.fa-refresh,.fa-solid.fa-sync{--aura-icon:...}
// so a line is kept when ANY name in its selector list is used. Lines 1-7 are
// the license header, the base .fa-solid/.fa-regular/.fa-brands rule and the
// spin/pulse keyframes; everything after is icon rules.
const ICON_RULE = /^\.fa-(?:solid|regular|brands)\.fa-[a-z0-9-]+(?:,\s*\.fa-(?:solid|regular|brands)\.fa-[a-z0-9-]+)*\{/;
const header = [];
const iconLines = [];
for (const line of lines) {
  if (ICON_RULE.test(line)) iconLines.push(line);
  else header.push(line);
}

// Rewrite the provenance comment so the generated file names its real generator.
const HEADER = [
  '/* Generated by scripts/prune-icons.mjs from tooling/icons-full.css.',
  '   Font Awesome Free 6.4.0: https://fontawesome.com — icons licensed CC BY 4.0;',
  '   see docs/licenses. Regenerate with `node scripts/prune-icons.mjs --apply`. */',
];
const baseRules = header.filter((line) => line.trim() && !line.startsWith('/*') && !line.startsWith('   '));

const defined = new Set();
const kept = [];
const dropped = [];
for (const line of iconLines) {
  const names = [...line.matchAll(/\.fa-(?:solid|regular|brands)\.fa-([a-z0-9-]+)/g)].map((m) => m[1]);
  for (const name of names) defined.add(name);
  if (names.some((name) => used.has(name))) kept.push(line);
  else dropped.push(...names);
}

const missing = [...used].filter((name) => !defined.has(name)).sort();
const keptBytes = kept.reduce((sum, line) => sum + line.length + 1, 0);
const fullBytes = full.length;

console.log(`defined: ${defined.size}   used: ${used.size}   kept: ${kept.length}   dropped: ${dropped.length}`);
console.log(`size: ${fullBytes} -> ${keptBytes} bytes (${Math.round((1 - keptBytes / fullBytes) * 100)}% smaller)`);
if (missing.length) {
  console.log(`\nused but NOT defined (check these by hand): ${missing.join(', ')}`);
}
if (dropped.length) {
  console.log(`\ndropped: ${dropped.sort().join(' ')}`);
}

if (process.argv.includes('--apply')) {
  const body = [...HEADER, ...baseRules].join('\n') + '\n' + kept.join('\n') + '\n';
  writeFileSync(OUT, body);
  console.log(`\nwrote ${OUT}`);
} else {
  console.log('\n(dry run; pass --apply to write)');
}
