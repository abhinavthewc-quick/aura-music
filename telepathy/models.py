"""Data schemas and types for the Telepathy Engine."""
from __future__ import annotations
from datetime import datetime
from typing import List, Optional, Literal
from pydantic import BaseModel, Field

# Psychological states
PsychologicalState = Literal[
    'late_night_introspection',
    'dopamine_hype',
    'melancholic_release',
    'deep_focus',
    'commute_cruise',
    'workout_aggression',
    'sunday_calm'
]

# Time blocks
TimeBlock = Literal[
    'early_morning',
    'morning_commute',
    'work_hours',
    'evening_commute',
    'night_wind_down',
    'late_night_3am'
]

# Day type
DayType = Literal['weekday', 'weekend']

# Audio routes
AudioRoute = Literal['headphones', 'car_bluetooth', 'phone_speaker', 'external_speaker']

# Event types
EventType = Literal[
    'SEARCH_AND_PLAY',
    'HERO_CARD_PLAY',
    'FULL_LISTEN',
    'VOLUME_SPIKE',
    'SCRUB_BACK',
    'LOOP_ENABLED',
    'INTERRUPTED_MIDWAY',
    'EARLY_SKIP'
]


class DSPMetrics(BaseModel):
    """Audio DSP metrics extracted via librosa."""
    bpm: float = Field(..., ge=0.0, description="Tempo in beats per minute")
    energy: float = Field(..., ge=0.0, le=1.0, description="Mean RMS energy normalized [0.0, 1.0]")
    acoustic_warmth: float = Field(..., ge=0.0, le=1.0, description="1.0 - normalized spectral centroid")
    onset_density: float = Field(..., ge=0.0, description="Rhythmic onsets per second")


class PsychoAcousticProfile(BaseModel):
    """Profile generated by the LLM psychologist."""
    valence: float = Field(..., ge=0.0, le=1.0, description="0.0 = sad/bleak, 1.0 = euphoric/joyful")
    arousal: float = Field(..., ge=0.0, le=1.0, description="0.0 = ambient/sleep, 1.0 = adrenaline-pumping")
    nostalgia_index: float = Field(..., ge=0.0, le=1.0, description="Likelihood of wistful/nostalgic memory")
    catharsis_score: float = Field(..., ge=0.0, le=1.0, description="Emotional release intensity")
    ego_boost: float = Field(..., ge=0.0, le=1.0, description="Confidence/swagger projection")
    focus_compatibility: float = Field(..., ge=0.0, le=1.0, description="Suitability for deep work")
    primary_psychological_state: PsychologicalState
    ideal_time_blocks: List[TimeBlock]
    ideal_weather: List[str]


class EnrichedTrackRecord(BaseModel):
    """Enriched track metadata record stored in tracks_enriched."""
    track_id: str
    song_name: str
    artist: str
    bpm: Optional[float] = None
    energy: Optional[float] = None
    acoustic_warmth: Optional[float] = None
    onset_density: Optional[float] = None
    valence: Optional[float] = None
    arousal: Optional[float] = None
    nostalgia_index: Optional[float] = None
    catharsis_score: Optional[float] = None
    ego_boost: Optional[float] = None
    focus_compatibility: Optional[float] = None
    primary_state: Optional[str] = None
    ideal_time_blocks: List[str] = Field(default_factory=list)
    ideal_weather: List[str] = Field(default_factory=list)
    psycho_vector: List[float] = Field(
        default_factory=list,
        description="8-dim vector: [energy, warmth, valence, arousal, nostalgia, catharsis, ego, focus]"
    )
    updated_at: Optional[datetime] = None


class TelemetryEvent(BaseModel):
    """Micro-telemetry interaction logged by client."""
    event_id: Optional[int] = None
    user_id: str
    track_id: str
    event_type: EventType
    completion_ratio: float = 0.0
    time_block: TimeBlock
    day_type: DayType
    audio_route: AudioRoute
    weather: str = "clear"
    created_at: Optional[datetime] = None


class MindReadRequest(BaseModel):
    """Real-time payload sent on app open."""
    user_id: str
    current_time_block: TimeBlock
    day_type: DayType
    audio_route: AudioRoute
    current_weather: str = "clear"


class HeroSlot1(BaseModel):
    """Slot #1 Hero Track prediction."""
    track_id: str
    song_name: str
    artist: str
    telepathy_score: float
    prebuffer_audio_bytes_url: str
    psychological_ui_badge: str


class OrthogonalPivot(BaseModel):
    """Slot #2 or Slot #3 orthogonal recommendation."""
    slot: int
    track_id: str
    ui_badge: str


class MindReadResponse(BaseModel):
    """Slot #1 telepathy prediction plus 2 orthogonal pivots."""
    hero_slot_1: HeroSlot1
    orthogonal_pivots: List[OrthogonalPivot]
